#pragma once

#include <cstdint>
#include <functional>

#include <drogon/orm/DbClient.h>

namespace para {

// ============================================================================
// ПРАВИЛО КОД-РЁВЬЮ (02 §6.3 п.3; гайд BE §4 Э2):
//
//   «Контроллер с path-id обязан вызвать OwnershipGuard».
//
// Любой эндпоинт, в пути которого есть {id} персонального объекта
// (applications/{id}, grades/{id}, notifications/{id}, ...), ДО любой
// отдачи данных обязан вызвать OwnershipGuard::check() и обработать
// Verdict. Исключить вызов невозможно технически — обеспечивает его
// код-ревью; все новые path-id эндпоинты идут через guard (Э4/Э5+).
// Маппинг Verdict → HTTP — в контроллере:
//   Own       → продолжить обработку;
//   NotFound  → 404 (02 §6.3: несуществующий объект);
//   Forbidden → 403 (02 §6.3: существующий чужой объект);
//   Error     → 500 (ошибка БД — не превращается в разрешение).
// Новый path-id объект добавляется одним значением в enum Table и одной
// фиксированной SQL-строкой в OwnershipGuard.cpp — логика guard'а не меняется.
// ============================================================================

class OwnershipGuard
{
  public:
    // Вердикт проверки владения (02 §6.3: чужое/несуществующее различаются,
    // подстановка адреса даёт 403 или 404).
    enum class Verdict
    {
        Own,        // объект существует и принадлежит сессии
        NotFound,   // объекта с таким id нет → 404
        Forbidden,  // объект существует, но принадлежит другому → 403
        Error,      // ошибка БД → 500, fail-closed (разрешением не считается)
    };

    // Белый список таблиц с user_id, доступных guard'у (02 §6.3 — path-id
    // объекты). Имя таблицы — НЕ параметр SQL и НЕ строка от клиента:
    // значение enum разворачивается в фиксированный SQL-литерал в .cpp
    // (switch), конкатенация строк в SQL запрещена (AGENTS §5.5, 02 §6.4).
    enum class Table
    {
        Applications,   // applications/{id}   (миграция 0003)
        Grades,         // grades/{id}         (миграция 0002)
        Notifications,  // notifications/{id}  (миграция 0004)
    };

    // Единственная функция guard'а (02 §6.3: «одна функция, проверяющая
    // владение до любой отдачи данных»).
    //
    // Выбранный вариант — fetch-and-compare из (sessionUserId, таблица,
    // id объекта), а не сравнение (sessionUserId, targetUserId): §6.3
    // определяет guard для объектов с id в пути — у контроллера на входе
    // только id из URL, поэтому guard сам достаёт user_id объекта
    // («SELECT user_id FROM <таблица> WHERE id = $1», id — параметром) и
    // различает NotFound (строки нет → 404) и Forbidden (строка чужая →
    // 403); вариант (sessionUserId, targetUserId) требует предварительной
    // загрузки объекта (владение проверялось бы уже после отдачи данных)
    // и 404 не различает. Скоуп в самом запросе (02 §6.3 п.2) остаётся в
    // сервисах: guard — третья ступень, а не замена WHERE user_id = :session.
    //
    // Стиль асинхронный, как у UserService (cb вызывается один раз; при
    // Error — тоже, после записи в лог).
    static void check(drogon::orm::DbClientPtr db,
                      Table table,
                      int64_t sessionUserId,
                      int64_t objectId,
                      std::function<void(Verdict)> cb);
};

}  // namespace para
